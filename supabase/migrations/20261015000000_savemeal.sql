create or replace function public.savemeal_submit_complaint(
  p_order_id bigint default null,
  p_listing_id bigint default null,
  p_category text default 'other',
  p_description text default '',
  p_photo_url text default ''
)
returns public.savemeal_complaints
language plpgsql
security definer
set search_path = ''
as $$
declare
  reporter_id uuid := (select auth.uid());
  result public.savemeal_complaints%rowtype;
begin
  if reporter_id is null or (p_order_id is null) = (p_listing_id is null) then
    raise exception 'Specify exactly one order or listing';
  end if;
  if p_category not in ('quality', 'delivery', 'safety', 'other')
     or length(trim(coalesce(p_description, ''))) < 10 then
    raise exception 'Invalid complaint details';
  end if;
  if p_order_id is not null and not exists (
    select 1 from public.savemeal_orders o
    where o.id = p_order_id and o.customer_id = reporter_id
  ) then
    raise exception 'You can only report your own order';
  end if;
  if p_listing_id is not null and not exists (
    select 1 from public.savemeal_listings l
    where l.id = p_listing_id and l.status = 'published'
  ) then
    raise exception 'Published listing not found';
  end if;

  insert into public.savemeal_complaints (
    order_id, listing_id, user_id, category, description, photo_url
  ) values (
    p_order_id, p_listing_id, reporter_id, p_category,
    trim(p_description), nullif(trim(coalesce(p_photo_url, '')), '')
  ) returning * into result;
  return result;
end;
$$;

