create or replace function public.savemeal_admin_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if not (select public.savemeal_is_admin()) then
    raise exception 'Administrator access required';
  end if;

  select jsonb_build_object(
    'stats', jsonb_build_object(
      'restaurantPending', (select count(*) from public.savemeal_profiles where role = 'restaurant' and not approved and is_active),
      'orgPending', (select count(*) from public.savemeal_profiles where role = 'organization' and not approved and is_active),
      'newComplaints', (select count(*) from public.savemeal_complaints where status = 'new'),
      'orders', (select count(*) from public.savemeal_orders where status <> 'cancelled'),
      'completedOrders', (select count(*) from public.savemeal_orders where status = 'completed'),
      'publishedListings', (select count(*) from public.savemeal_listings where status = 'published'),
      'donatedPortions', (select coalesce(sum(portions), 0) from public.savemeal_donation_requests where status = 'completed'),
      'mealsRescued', (select coalesce(sum(quantity), 0) from public.savemeal_orders where status = 'completed')
    ),
    'pendingUsers', coalesce((
      select jsonb_agg(to_jsonb(p) order by p.created_at desc)
      from (
        select id, name, email, role, approved, organization_name, city, phone,
          restaurant_address, restaurant_image_url, owner_name, owner_phone,
          verification_status, verification_note, restaurant_document_path,
          organization_document_path, created_at
        from public.savemeal_profiles
        where role in ('restaurant', 'organization') and not approved and is_active
      ) p
    ), '[]'::jsonb),
    'pendingListings', coalesce((
      select jsonb_agg(to_jsonb(l) order by l.created_at desc)
      from (
        select listing.*, coalesce(nullif(profile.organization_name, ''), profile.name) as restaurant_name
        from public.savemeal_listings listing
        join public.savemeal_profiles profile on profile.id = listing.restaurant_id
        where listing.status = 'pending_review'
      ) l
    ), '[]'::jsonb),
    'complaints', coalesce((
      select jsonb_agg(to_jsonb(c) order by c.created_at desc)
      from (
        select complaint.*, listing.title as listing_title
        from public.savemeal_complaints complaint
        left join public.savemeal_listings listing on listing.id = complaint.listing_id
        order by complaint.created_at desc
        limit 20
      ) c
    ), '[]'::jsonb)
  ) into result;

  return result;
end;
$$;

