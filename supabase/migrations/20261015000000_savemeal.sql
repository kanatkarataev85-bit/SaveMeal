create or replace view public.savemeal_public_listings
with (security_barrier = true)
as
select
  l.id, l.title, l.description, l.category, l.service_type, l.price,
  l.original_price, l.portions, l.available_portions, l.allergens, l.ingredients,
  l.pickup_window, l.best_before, l.storage_instructions, l.image_url,
  l.pickup_available, l.delivery_available, l.delivery_area, l.delivery_fee,
  l.is_anonymous, l.status, l.created_at, l.updated_at,
  case
    when l.is_anonymous then 'Анонимный партнер'
    else coalesce(nullif(p.organization_name, ''), p.name)
  end as restaurant_name
from public.savemeal_listings l
join public.savemeal_profiles p on p.id = l.restaurant_id
where l.status = 'published';

create or replace view public.savemeal_public_stats
with (security_barrier = true)
as
select
  (select count(*) from public.savemeal_listings where status = 'published') as published_listings,
  (select count(*) from public.savemeal_orders where status <> 'cancelled') as total_orders,
  (select count(*) from public.savemeal_orders where status = 'completed') as completed_orders,
  (select coalesce(sum(quantity), 0) from public.savemeal_orders where status = 'completed') as meals_rescued,
  (select count(*) from public.savemeal_profiles where role = 'restaurant' and approved and is_active) as restaurants,
  (select count(*) from public.savemeal_profiles where role = 'organization' and approved and is_active) as organizations,
  (select coalesce(sum(portions), 0) from public.savemeal_donation_requests where status = 'completed') as donated_portions;

