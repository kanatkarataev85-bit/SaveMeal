create or replace function public.savemeal_create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_role text;
  assigned_role text;
  is_approved boolean;
begin
  requested_role := coalesce(new.raw_user_meta_data ->> 'role', 'customer');

  if requested_role not in ('customer', 'restaurant', 'organization') then
    requested_role := 'customer';
  end if;

  if exists (
    select 1 from public.savemeal_admin_allowlist a
    where a.email = lower(new.email)
  ) then
    assigned_role := 'administrator';
    is_approved := true;
  else
    assigned_role := requested_role;
    is_approved := requested_role = 'customer';
  end if;

  insert into public.savemeal_profiles (
    id, name, email, role, approved, organization_name, city, phone,
    owner_name, owner_phone, restaurant_address, restaurant_image_url,
    restaurant_document_path, organization_document_path, verification_status
  ) values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1)),
    lower(new.email),
    assigned_role,
    is_approved,
    nullif(new.raw_user_meta_data ->> 'organization_name', ''),
    nullif(new.raw_user_meta_data ->> 'city', ''),
    nullif(new.raw_user_meta_data ->> 'phone', ''),
    nullif(new.raw_user_meta_data ->> 'owner_name', ''),
    nullif(new.raw_user_meta_data ->> 'owner_phone', ''),
    nullif(new.raw_user_meta_data ->> 'restaurant_address', ''),
    nullif(new.raw_user_meta_data ->> 'restaurant_image_url', ''),
    nullif(new.raw_user_meta_data ->> 'restaurant_document_path', ''),
    nullif(new.raw_user_meta_data ->> 'organization_document_path', ''),
    case when assigned_role in ('restaurant', 'organization') then 'pending' else 'not_required' end
  );

  return new;
end;
$$;

