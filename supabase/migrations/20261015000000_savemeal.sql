create or replace function public.savemeal_create_order(
  p_listing_id bigint,
  p_quantity integer,
  p_pickup_type text,
  p_delivery_address text default '',
  p_notes text default ''
)
returns public.savemeal_orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  buyer_id uuid := (select auth.uid());
  item public.savemeal_listings%rowtype;
  buyer public.savemeal_profiles%rowtype;
  result public.savemeal_orders%rowtype;
  item_subtotal integer;
  fee integer;
begin
  if buyer_id is null or p_quantity < 1 or p_pickup_type not in ('pickup', 'delivery') then
    raise exception 'Invalid order request';
  end if;

  select * into buyer from public.savemeal_profiles where id = buyer_id for share;
  if not found or buyer.role <> 'customer' or not buyer.approved or not buyer.is_active then
    raise exception 'An active customer account is required';
  end if;

  select * into item from public.savemeal_listings where id = p_listing_id for update;
  if not found or item.status <> 'published' or item.service_type <> 'sale' then
    raise exception 'Listing is not available for ordering';
  end if;
  if item.available_portions < p_quantity then
    raise exception 'Not enough portions available';
  end if;
  if p_pickup_type = 'pickup' and not item.pickup_available then
    raise exception 'Pickup is not available for this listing';
  end if;
  if p_pickup_type = 'delivery' and (not item.delivery_available or length(trim(coalesce(p_delivery_address, ''))) < 5) then
    raise exception 'A valid delivery address is required';
  end if;

  item_subtotal := item.price * p_quantity;
  fee := case when p_pickup_type = 'delivery' then item.delivery_fee else 0 end;

  update public.savemeal_listings
  set available_portions = available_portions - p_quantity,
      status = case when available_portions - p_quantity = 0 then 'sold_out' else status end,
      updated_at = now()
  where id = item.id;

  insert into public.savemeal_orders (
    customer_id, restaurant_id, listing_id, quantity, subtotal, delivery_fee,
    total_price, pickup_type, delivery_address, notes
  ) values (
    buyer_id, item.restaurant_id, item.id, p_quantity, item_subtotal, fee,
    item_subtotal + fee, p_pickup_type, coalesce(p_delivery_address, ''), coalesce(p_notes, '')
  ) returning * into result;

  insert into public.savemeal_audit_logs (actor_id, action, details)
  values (buyer_id, 'order_created', jsonb_build_object('order_id', result.id, 'listing_id', item.id));
  return result;
end;
$$;

create or replace function public.savemeal_transition_order(
  p_order_id bigint,
  p_status text,
  p_reason text default ''
)
returns public.savemeal_orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := (select auth.uid());
  current_order public.savemeal_orders%rowtype;
  actor public.savemeal_profiles%rowtype;
  valid_transition boolean;
  permitted boolean := false;
begin
  select * into current_order from public.savemeal_orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found';
  end if;
  select * into actor from public.savemeal_profiles where id = actor_id;
  if not found or not actor.is_active then
    raise exception 'Active account required';
  end if;

  valid_transition :=
    (current_order.status = 'pending_confirmation' and p_status in ('confirmed', 'cancelled'))
    or (current_order.status = 'confirmed' and p_status in ('preparing', 'cancelled'))
    or (current_order.status = 'preparing' and p_status in ('ready', 'cancelled'))
    or (current_order.status = 'ready' and p_status in ('completed', 'cancelled'))
    or (current_order.status = 'completed' and p_status = 'refunded');

  permitted := valid_transition and (
      (select public.savemeal_is_admin())
      or (actor.role = 'restaurant' and current_order.restaurant_id = actor_id
        and current_order.status in ('pending_confirmation', 'confirmed', 'preparing', 'ready')
        and p_status = case current_order.status
          when 'pending_confirmation' then 'confirmed'
          when 'confirmed' then 'preparing'
          when 'preparing' then 'ready'
          when 'ready' then 'completed'
          else '' end)
      or (actor.role = 'customer' and current_order.customer_id = actor_id
        and current_order.status in ('pending_confirmation', 'confirmed')
        and p_status = 'cancelled')
    );

  if not permitted then
    raise exception 'Order status transition is not permitted';
  end if;

  update public.savemeal_orders
  set status = p_status, updated_at = now()
  where id = p_order_id
  returning * into current_order;

  if p_status in ('cancelled', 'refunded') then
    update public.savemeal_listings
    set available_portions = least(portions, available_portions + current_order.quantity),
        status = case when status = 'sold_out' then 'published' else status end,
        updated_at = now()
    where id = current_order.listing_id;
  end if;

  insert into public.savemeal_audit_logs (actor_id, action, details)
  values (actor_id, 'order_status_changed',
    jsonb_build_object('order_id', p_order_id, 'status', p_status, 'reason', coalesce(p_reason, '')));
  return current_order;
end;
$$;

create or replace function public.savemeal_request_donation(
  p_listing_id bigint,
  p_portions integer,
  p_notes text default ''
)
returns public.savemeal_donation_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  organization_id uuid := (select auth.uid());
  item public.savemeal_listings%rowtype;
  result public.savemeal_donation_requests%rowtype;
begin
  if organization_id is null or p_portions < 1 then
    raise exception 'Invalid donation request';
  end if;
  if not (select public.savemeal_is_approved_organization()) then
    raise exception 'A verified organization account is required';
  end if;

  select * into item from public.savemeal_listings where id = p_listing_id for share;
  if not found or item.status <> 'published' or item.service_type <> 'donation' then
    raise exception 'Donation is not available';
  end if;
  if item.available_portions < p_portions then
    raise exception 'Not enough portions available';
  end if;
  if exists (
    select 1 from public.savemeal_donation_requests r
    where r.organization_id = organization_id and r.listing_id = item.id
      and r.status in ('pending', 'approved')
  ) then
    raise exception 'An active request already exists';
  end if;

  insert into public.savemeal_donation_requests (organization_id, listing_id, portions, notes)
  values (organization_id, item.id, p_portions, coalesce(p_notes, ''))
  returning * into result;
  return result;
end;
$$;

create or replace function public.savemeal_transition_donation(
  p_request_id bigint,
  p_status text,
  p_reason text default ''
)
returns public.savemeal_donation_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := (select auth.uid());
  request_row public.savemeal_donation_requests%rowtype;
  item public.savemeal_listings%rowtype;
  actor public.savemeal_profiles%rowtype;
  is_owner boolean;
begin
  select * into request_row from public.savemeal_donation_requests
  where id = p_request_id for update;
  if not found then
    raise exception 'Donation request not found';
  end if;
  select * into item from public.savemeal_listings where id = request_row.listing_id for update;
  select * into actor from public.savemeal_profiles where id = actor_id;
  is_owner := actor.role = 'restaurant' and item.restaurant_id = actor_id;

  if not found or not actor.is_active then
    raise exception 'Active account required';
  end if;
  if not (select public.savemeal_is_admin()) and not is_owner
     and not (actor.role = 'organization' and request_row.organization_id = actor_id) then
    raise exception 'Not permitted to manage this request';
  end if;

  if request_row.status = 'pending' and p_status in ('approved', 'rejected') then
    if p_status = 'approved' then
      if not is_owner and not (select public.savemeal_is_admin()) then
        raise exception 'Only the restaurant or an administrator can approve';
      end if;
      if item.available_portions < request_row.portions then
        raise exception 'Not enough portions available';
      end if;
      update public.savemeal_listings
      set available_portions = available_portions - request_row.portions,
          updated_at = now()
      where id = item.id;
    elsif not is_owner and not (select public.savemeal_is_admin()) then
      raise exception 'Only the restaurant or an administrator can reject';
    end if;
  elsif request_row.status = 'approved' and p_status = 'collected' then
    if actor.role <> 'organization' or request_row.organization_id <> actor_id then
      raise exception 'Only the requesting organization can mark collection';
    end if;
  elsif request_row.status = 'collected' and p_status = 'completed' then
    if not is_owner and not (select public.savemeal_is_admin()) then
      raise exception 'Only the restaurant or an administrator can complete the request';
    end if;
  elsif request_row.status = 'approved' and p_status = 'rejected' then
    if not is_owner and not (select public.savemeal_is_admin()) then
      raise exception 'Only the restaurant or an administrator can reverse approval';
    end if;
    update public.savemeal_listings
    set available_portions = least(portions, available_portions + request_row.portions),
        updated_at = now()
    where id = item.id;
  else
    raise exception 'Invalid donation status transition';
  end if;

  update public.savemeal_donation_requests
  set status = p_status,
      notes = case when nullif(trim(coalesce(p_reason, '')), '') is null
        then notes else concat_ws(E'\n', notes, 'Причина: ' || trim(p_reason)) end,
      updated_at = now()
  where id = p_request_id
  returning * into request_row;

  insert into public.savemeal_audit_logs (actor_id, action, details)
  values (actor_id, 'donation_status_changed',
    jsonb_build_object('request_id', p_request_id, 'status', p_status));
  return request_row;
end;
$$;

create or replace function public.savemeal_moderate_listing(
  p_listing_id bigint,
  p_decision text,
  p_reason text default ''
)
returns public.savemeal_listings
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.savemeal_listings%rowtype;
begin
  if not (select public.savemeal_is_admin()) then
    raise exception 'Administrator access required';
  end if;
  if p_decision not in ('approve', 'reject') then
    raise exception 'Invalid moderation decision';
  end if;

  update public.savemeal_listings
  set status = case when p_decision = 'approve' then 'published' else 'suspended' end,
      rejection_reason = case when p_decision = 'reject' then nullif(trim(p_reason), '') else null end,
      updated_at = now()
  where id = p_listing_id and status = 'pending_review'
  returning * into result;
  if not found then
    raise exception 'Pending listing not found';
  end if;

  insert into public.savemeal_audit_logs (actor_id, action, details)
  values ((select auth.uid()), 'listing_moderated',
    jsonb_build_object('listing_id', p_listing_id, 'decision', p_decision, 'reason', coalesce(p_reason, '')));
  return result;
end;
$$;

