create or replace function public.savemeal_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.savemeal_profiles p
    join auth.users u on u.id = p.id
    join public.savemeal_admin_allowlist a on a.email = lower(u.email)
    where p.id = (select auth.uid())
      and p.role = 'administrator'
      and p.is_active
  );
$$;

