create table if not exists public.savemeal_admin_allowlist (
  email text primary key,
  created_at timestamptz not null default now(),
  constraint savemeal_admin_allowlist_email_lowercase check (email = lower(email))
);

create table if not exists public.savemeal_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id bigint unique,
  name text not null,
  email text unique,
  role text not null check (role in ('customer', 'restaurant', 'organization', 'administrator')),
  approved boolean not null default false,
  is_active boolean not null default true,
  phone text,
  city text,
  organization_name text,
  restaurant_address text,
  restaurant_image_url text,
  owner_name text,
  owner_phone text,
  verification_status text not null default 'not_required'
    check (verification_status in ('not_required', 'pending', 'approved', 'rejected')),
  verification_note text,
  restaurant_document_path text,
  organization_document_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.savemeal_listings (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  restaurant_id uuid not null references public.savemeal_profiles(id),
  title text not null,
  description text not null,
  category text not null,
  service_type text not null check (service_type in ('sale', 'donation')),
  price integer not null default 0 check (price >= 0),
  original_price integer not null default 0 check (original_price >= 0),
  portions integer not null check (portions > 0),
  available_portions integer not null check (available_portions >= 0 and available_portions <= portions),
  allergens text not null default '',
  ingredients text not null default '',
  pickup_window text not null,
  best_before text,
  storage_instructions text not null default '',
  image_url text,
  pickup_available boolean not null default true,
  delivery_available boolean not null default false,
  delivery_area text not null default '',
  delivery_fee integer not null default 0 check (delivery_fee >= 0),
  is_anonymous boolean not null default false,
  status text not null default 'pending_review'
    check (status in ('draft', 'pending_review', 'published', 'sold_out', 'expired', 'suspended')),
  rejection_reason text,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint savemeal_listing_pickup_method check (pickup_available or delivery_available),
  constraint savemeal_listing_sale_price check (service_type = 'donation' or original_price >= price)
);

create table if not exists public.savemeal_orders (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  customer_id uuid not null references public.savemeal_profiles(id),
  restaurant_id uuid not null references public.savemeal_profiles(id),
  listing_id bigint not null references public.savemeal_listings(id),
  quantity integer not null check (quantity > 0),
  subtotal integer not null check (subtotal >= 0),
  delivery_fee integer not null default 0 check (delivery_fee >= 0),
  total_price integer not null check (total_price = subtotal + delivery_fee),
  status text not null default 'pending_confirmation'
    check (status in ('pending_confirmation', 'confirmed', 'preparing', 'ready', 'completed', 'cancelled', 'refunded')),
  pickup_type text not null check (pickup_type in ('pickup', 'delivery')),
  delivery_address text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.savemeal_donation_requests (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  organization_id uuid not null references public.savemeal_profiles(id),
  listing_id bigint not null references public.savemeal_listings(id),
  portions integer not null default 1 check (portions > 0),
  notes text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'collected', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.savemeal_complaints (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  order_id bigint references public.savemeal_orders(id),
  listing_id bigint references public.savemeal_listings(id),
  user_id uuid not null references public.savemeal_profiles(id),
  category text not null check (category in ('quality', 'delivery', 'safety', 'other')),
  description text not null,
  photo_url text,
