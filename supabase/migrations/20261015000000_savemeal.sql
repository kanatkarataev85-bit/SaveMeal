create or replace function public.savemeal_requeue_listing_edit()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if row(
    new.title, new.description, new.category, new.service_type, new.price,
    new.original_price, new.portions, new.allergens,
    new.ingredients, new.pickup_window, new.best_before, new.storage_instructions,
